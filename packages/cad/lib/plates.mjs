// A machine's printed parts on beds: each object in its print orientation (as it's drawn, Z up, on the bed), grouped by
// filament, spaced by the first-layer rule, and written as plate assemblies, so check and export treat them as prints.
// Each plate remembers what's on it by the build's hash ("packed"): a changed part re-packs only its plate.
import fs from 'node:fs';
import path from 'node:path';
import { bounds, check as printCheck } from '@rulecad/printcheck';
import { locate, build } from './design.mjs';
import { paths, printerOf } from './workspace.mjs';
import { peekRuleSet } from './rules.mjs';
import { CadError } from './errors.mjs';
import { assemblyPath, buildAssembly, checkAssembly } from './assembly.mjs';
import { printedParts } from './list.mjs';

const n3 = (x) => +x.toFixed(3);

// The gap between parts on a plate: what two parts need to print apart at the first layer (print_gap, plus the first
// layer's spread each side), up to whole lines of the nozzle
function rulesOf(project, gap) {
  const r = peekRuleSet(printerOf(project)).rules, num = (k, f) => { const v = r[k]?.value; return typeof v === 'number' ? v : f; }, bed = num('bed', 256), line = num('line', 0.42), need = num('print_gap', 0.3) + 2 * num('foot', 0.15);
  return { bed, gap: gap ?? n3(Math.ceil((need - 1e-6) / line) * line), need };
}

// Every printed thing to go on a plate: built as printed, its filaments, how big
async function plateParts(s) {
  const out = [];
  for (const o of s.objects) {
    if (o.unplaced || o.role !== 'part' || !o.objName) continue;
    const d = locate(`${s.project}/${o.objName}`), b = await build({ ...d, ...(o.variant ? { variant: o.variant } : {}) }, o.set || {}), tris = b.parts.flatMap((p) => p.triangles), { lo, hi } = bounds(tris);
    const fil = [...new Set(b.parts.filter((p) => p.role !== 'support').map((p) => p.filament || 'base'))].sort().join('+') || 'base';
    out.push({ id: o.id.replace(/\./g, '_'), source: o.id, object: o.objName, variant: o.variant, set: o.set || {}, filament: fil, hash: b.hash, lo, size: [hi[0] - lo[0], hi[1] - lo[1]], height: hi[2] - lo[2] });
  }
  return out;
}

// Shelves on a bed, largest first: as many plates as it takes
function pack(parts, { bed, gap }) {
  const sorted = [...parts].sort((a, b) => b.size[1] - a.size[1] || b.size[0] - a.size[0] || a.id.localeCompare(b.id)), beds = [];
  const room = bed - 2 * gap;
  for (const p of sorted) {
    let done = false;
    for (const b of beds) {
      const shelf = b.shelves.at(-1);
      if (shelf.x + p.size[0] <= room && p.size[1] <= shelf.h) { b.items.push({ p, x: shelf.x, y: shelf.y }); shelf.x += p.size[0] + gap; done = true; break; }
      const y = shelf.y + shelf.h + gap;
      if (y + p.size[1] <= room && p.size[0] <= room) { b.shelves.push({ y, h: p.size[1], x: p.size[0] + gap }); b.items.push({ p, x: 0, y }); done = true; break; }
    }
    if (!done) beds.push({ shelves: [{ y: 0, h: p.size[1], x: p.size[0] + gap }], items: [{ p, x: 0, y: 0 }] });
  }
  return beds;
}

const plateFile = (project, name) => assemblyPath(`${project}/${name}`);
function existing(s) {
  const dir = path.join(paths.project(s.project), 'assemblies'), out = [];
  for (const f of fs.existsSync(dir) ? fs.readdirSync(dir) : []) { if (!f.endsWith('.json')) continue; let a; try { a = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')); } catch { continue; } if (a.packed?.of === s.name) out.push({ name: f.slice(0, -5), a }); }
  return out.sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }));
}
const nameOf = (s, filament, k) => `${s.name}-${filament.replace(/\+/g, '-')}-${k}`;

function plateJson(s, plate, { bed, gap }) {
  const origin = (bed - 2 * gap) / 2;
  return { title: `${s.a.title || s.name}: ${plate.filament}, plate ${plate.n}`, kind: 'plate', note: `Generated by cad plates from ${s.name}. Hand edits are replaced when a part on it changes.`,
    packed: { of: s.name, filament: plate.filament, gap, parts: Object.fromEntries(plate.items.map(({ p }) => [p.id, p.hash])) },
    items: plate.items.map(({ p, x, y }) => ({ id: p.id, object: p.object, ...(p.variant ? { variant: p.variant } : {}), ...(Object.keys(p.set).length ? { set: p.set } : {}), at: [n3(x - origin - p.lo[0]), n3(y - origin - p.lo[1]), n3(-p.lo[2])] })) };
}

/**
 * The plates of an assembly: a stale plate (a part on it changed or gone) and any new part packed again, every other plate left alone.
 * @param {object} s a built assembly @param {{ write?: boolean, gap?: number }} [options]
 * @returns {Promise<{ plates: object[], touched: string[], removed: string[], gap: number, bed: number, findings: object[] }>}
 */
export async function platesOf(s, { write = false, gap: asked } = {}) {
  const parts = await plateParts(s), { bed, gap } = rulesOf(s.project, asked), findings = [], plates = [], touched = [], removed = [];
  if (!parts.length) throw new CadError('plates.empty', `${s.project}/${s.name} has nothing printed to put on a plate`);
  const big = parts.filter((p) => p.size[0] > bed - 2 * gap || p.size[1] > bed - 2 * gap);
  for (const p of big) findings.push({ level: 'fail', text: `${p.id} (${p.object}) is ${Number(p.size[0].toFixed(1))} × ${Number(p.size[1].toFixed(1))} mm: bigger than the ${bed} mm bed, so it has no plate: split it or turn it`, code: 'plate.bed', refs: { item: p.id }, values: { size: p.size, bed } });
  const by = new Map(parts.filter((p) => !big.includes(p)).map((p) => [p.id, p])), had = existing(s), kept = new Set(), used = new Set();
  // A plate stands if everything on it is still there and unchanged
  for (const e of had) {
    const on = Object.entries(e.a.packed.parts || {}), ok = on.length && on.every(([id, h]) => by.get(id)?.hash === h) && e.a.packed.gap === gap;
    if (!ok) continue;
    kept.add(e.name); on.forEach(([id]) => used.add(id)); plates.push({ name: e.name, filament: e.a.packed.filament, a: e.a, items: e.a.items.map((it) => { const p = by.get(it.id), origin = (bed - 2 * gap) / 2; return { p, x: it.at[0] + p.lo[0] + origin, y: it.at[1] + p.lo[1] + origin }; }), stood: true });
  }
  // Everything else, packed by filament; names reused from the plates that are going, so a changed part keeps its name
  const free = [...by.values()].filter((p) => !used.has(p.id)), byFilament = new Map();
  for (const p of free) { if (!byFilament.has(p.filament)) byFilament.set(p.filament, []); byFilament.get(p.filament).push(p); }
  const goingNames = had.filter((e) => !kept.has(e.name)).map((e) => e.name);
  for (const [filament, list] of byFilament) {
    const beds = pack(list, { bed, gap }); let k = 0;
    const next = () => { const reuse = goingNames.find((n) => had.find((e) => e.name === n)?.a.packed.filament === filament); if (reuse) { goingNames.splice(goingNames.indexOf(reuse), 1); return reuse; } let name; do name = nameOf(s, filament, ++k); while (kept.has(name) || plates.some((x) => x.name === name)); return name; };
    for (const b of beds) { const name = next(), n = Number(name.match(/-(\d+)$/)?.[1]) || 1, plate = { name, filament, n, items: b.items }; plate.a = plateJson(s, plate, { bed, gap }); plates.push(plate); touched.push(name); }
  }
  for (const n of goingNames) removed.push(n);
  plates.sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }));
  if (write) {
    const dir = path.join(paths.project(s.project), 'assemblies'); fs.mkdirSync(dir, { recursive: true });
    for (const p of plates) if (!p.stood) fs.writeFileSync(plateFile(s.project, p.name), `${JSON.stringify(p.a, null, 2)}\n`);
    for (const n of removed) fs.rmSync(plateFile(s.project, n), { force: true });
  }
  const grams = new Map(printedParts(s).map((x) => [x.id.replace(/\./g, '_'), x]));
  return { bed, gap, touched, removed, findings, plates: plates.map((p) => ({ name: p.name, filament: p.filament, parts: p.items.map(({ p: q, x, y }) => ({ id: q.id, object: q.object, x: n3(x + gap), y: n3(y + gap), w: n3(q.size[0]), d: n3(q.size[1]) })), grams: n3(p.items.reduce((t, { p: q }) => t + (grams.get(q.id)?.grams ?? 0), 0)), minutes: p.items.reduce((t, { p: q }) => t + (grams.get(q.id)?.minutes ?? 0), 0), stood: !!p.stood })) };
}

/** Each plate's checks: what check says of a plate, the print check over the whole bed included. */
export async function checkPlate(ref) {
  const s = await buildAssembly(ref), printer = printerOf(s.project), rules = Object.fromEntries(Object.keys(peekRuleSet(printer).rules).map((k) => [k, s.num(`${printer}.${k}`)])), printed = s.parts.filter((p) => p.role !== 'reference');
  return [...checkAssembly(s), ...printCheck(printed.flatMap((p) => p.triangles), rules, { parts: printed })];
}
